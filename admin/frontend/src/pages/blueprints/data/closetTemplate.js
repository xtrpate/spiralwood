export function createClosetWardrobeComponents(
  originX,
  originZ,
  canvasH,
  groupId,
  groupLabel,
) {
  const floorY = canvasH - FLOOR_OFFSET;
  const topY = floorY - CUSTOMER_WARDROBE_BOUNDS.height;

  return CUSTOMER_PREVIEW_PARTS.map((savedPart) =>
    createAssemblyPart({
      ...savedPart.data,

      id: makeId(),
      assemblyId: groupId,
      assemblyName: groupLabel,
      groupId,
      groupLabel,
      groupType: "assembly",

      x: originX + savedPart.dx,
      y: topY + savedPart.dy,
      z: originZ + savedPart.dz,
    }),
  );
}
